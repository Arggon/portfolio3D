#!/usr/bin/env node
// Refresh web/fallback.js from the public GitHub API.
//
//   node scripts/snapshot.mjs
//
// The site works without running this: the browser also fetches live data.
// This file keeps the offline snapshot in sync when project metadata changes.

import { writeFile } from "node:fs/promises";

const USER = "Arggon";
const GITHUB_URL = `https://github.com/${USER}`;
const CV_URL = `https://github.com/${USER}/arggon-cv`;
const REPOS = [
  "dotnet-batchyard",
  "cuentas-claras",
  "suizo",
  "racha",
  "estanteria",
  "ember-ascent",
];

const headers = {
  Accept: "application/vnd.github+json",
  "User-Agent": "arggon-portfolio3d-snapshot",
};
if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

const res = await fetch(
  `https://api.github.com/users/${USER}/repos?per_page=100&sort=updated`,
  { headers },
);

if (!res.ok) {
  throw new Error(`GitHub API returned ${res.status} ${res.statusText}`);
}

const repos = await res.json();
const byName = new Map(repos.map((repo) => [repo.name, repo]));

const missing = REPOS.filter((name) => !byName.has(name));
if (missing.length) {
  throw new Error(`Missing public repositories: ${missing.join(", ")}`);
}

const projects = REPOS.map((name) => {
  const repo = byName.get(name);
  return {
    name: repo.name,
    description: repo.description,
    language: repo.language,
    stars: repo.stargazers_count,
    forks: repo.forks_count,
    homepage: repo.homepage,
    topics: repo.topics ?? [],
    updated: (repo.updated_at ?? "").slice(0, 10),
    url: repo.html_url,
  };
});

const body = `// Generated by scripts/snapshot.mjs from the public GitHub API.
// This is the offline snapshot; the page still refreshes from GitHub live.
export const GITHUB_USER = ${JSON.stringify(USER)};
export const GITHUB_URL = ${JSON.stringify(GITHUB_URL)};
export const CV_URL = ${JSON.stringify(CV_URL)};
export const SNAPSHOT_AT = ${JSON.stringify(new Date().toISOString())};
export const PROJECTS = ${JSON.stringify(projects, null, 2)};
`;

await writeFile(new URL("../web/fallback.js", import.meta.url), body);
console.log(`Wrote ${projects.length} projects to web/fallback.js`);
